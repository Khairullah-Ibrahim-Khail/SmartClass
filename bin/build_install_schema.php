<?php
// Builds config/install_schema.sql — the schema of a NEW customer: every table, no sample rows, no
// CREATE DATABASE / USE. Run again after the schema file changes:   php bin/build_install_schema.php
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
// STOP: smartclass_db.sql is the OLD base schema (before migrations 044-054); config/install_schema.sql is now kept up to date by hand with every migration
// (see docs/ARCHITECTURE.md), so rebuilding it from smartclass_db.sql would silently drop those tables and columns. Only run with --force on purpose.
if (!in_array('--force', $argv ?? [], true)) { fwrite(STDERR, "Refusing: this would overwrite config/install_schema.sql with an older schema. Use --force only if you know why.\n"); exit(1); }
$src = file_get_contents(dirname(__DIR__) . '/config/smartclass_db.sql');
$src = preg_replace('#/\*.*?\*/#s', '', $src);
$keep = [];
foreach (preg_split('/;\s*\n/', $src) as $stmt) {
    $lines = array_filter(array_map('trim', explode("\n", $stmt)), fn($l) => $l !== '' && strpos($l, '--') !== 0);
    $body = trim(implode("\n", $lines));
    if ($body === '') continue;
    if (preg_match('/^(CREATE DATABASE|USE|INSERT|UPDATE|DELETE|REPLACE)\b/i', $body)) continue;   // sample data / database selection
    $keep[] = $body . ';';
}
$out = "-- SmartClass schema for a new customer (generated by bin/build_install_schema.php from smartclass_db.sql — do not edit)\n" . implode("\n\n", $keep) . "\n";
file_put_contents(dirname(__DIR__) . '/config/install_schema.sql', $out);
echo count($keep) . " statements written to config/install_schema.sql\n";
