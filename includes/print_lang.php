/**
 * SmartClass - print language (loaded by includes/functions.php)
 * Print pages can be shown in English, Pashto (پښتو) or Dari (دری); Pashto and Dari print right-to-left.
 *   printLang()      reads ?lang=ps|fa (anything else = en) → ['lang', 'rtl']
 *   pt($english)     the text in the chosen language (English when there is no translation)
 *   pdate($d, $time) a date: "Oct 25, 2026" in English, 2026-10-25 in Pashto / Dari
 *   printLangBar()   the language links for the grey bar on top of a print page
 *   printLangCss()   right-to-left rules + Arabic-script fonts (add inside <style>)
 * Used by the grades, final marks and school report prints (the attendance report and the class list carry the same idea inline).
 */
function printLang() {
    static $r = null;
    if ($r === null) {
        $l = in_array($_GET['lang'] ?? '', ['ps', 'fa'], true) ? $_GET['lang'] : 'en';
        $r = ['lang' => $l, 'rtl' => $l !== 'en'];
    }
    return $r;
}

