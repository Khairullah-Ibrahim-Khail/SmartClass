function pt($english) {
    $p = printLang();
    if (!$p['rtl']) return $english;
    $t = printTranslations()[$english] ?? null;
    return $t ? $t[$p['lang'] === 'ps' ? 0 : 1] : $english;
}

function pdate($d, $time = false) {
    $ts = strtotime((string) $d);
    if (printLang()['rtl']) return date($time ? 'Y-m-d H:i' : 'Y-m-d', $ts);
    return date($time ? 'M j, Y, g:i A' : 'M j, Y', $ts);
}

function printLangBar() {
    $cur = printLang()['lang'];
    $h = '';
    foreach (['en' => 'English', 'ps' => 'پښتو', 'fa' => 'دری'] as $c => $n) {
        $h .= '<a class="ghost" style="' . ($c === $cur ? 'background:rgba(255,255,255,.18);' : '') . '" href="?' . htmlspecialchars(http_build_query(array_merge($_GET, ['lang' => $c]))) . '">' . $n . '</a> ';
    }
    return $h;
}

function printLangCss() {
    if (!printLang()['rtl']) return '';
    return 'body { font-family: "Noto Naskh Arabic", "Noto Sans Arabic", "Amiri", Tahoma, "Segoe UI", Arial, sans-serif; }'
        . ' header.doc .right { margin-left: 0; margin-right: auto; text-align: left; }'
        . ' td.name, th.name, .fb { text-align: right; } .line .kv { margin-right: 0; margin-left: 18px; white-space: normal; }'
        . ' header.doc .school, .meta small { text-transform: none; letter-spacing: 0; } .bars div { direction: rtl; } .gcv, td.cellbg { direction: ltr; unicode-bidi: isolate; }';
}
